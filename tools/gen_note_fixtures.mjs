#!/usr/bin/env node
// Generates BibleWish/Sync/NoteInlineFixtures.swift: how the website's own note formatter
// (js/note-format.js, its real INLINE_PATTERN, loaded from the file) splits a set of tricky lines into
// bold, italic, links, colors and highlights. The app's Debug self-test checks its parser against
// these, so the two can't drift apart silently. Re-run it when the website's note syntax changes.
//
//   node tools/gen_note_fixtures.mjs [path/to/BibleWish_Website]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const site = process.argv[2] ?? join(root, '..', 'BibleWish_Website');
const source = readFileSync(join(site, 'js', 'note-format.js'), 'utf8');

// The website's own pattern, taken from its source.
const NOTE_COLORS = [...source.matchAll(/\{ id: '(\w+)', label: '\w+' \}/g)].map(match => ({ id: match[1] }))
    .filter(color => ['red', 'gold', 'green', 'teal', 'violet'].includes(color.id));
const body = source.match(/const INLINE_PATTERN = new RegExp\(\[([\s\S]*?)\]\.join\('\|'\), 'gu'\);/)[1];
const INLINE_PATTERN = eval(`new RegExp([${body}].join('|'), 'gu')`);

function tokens(text) {
    const out = [];
    let last = 0;
    for (const match of text.matchAll(INLINE_PATTERN)) {
        if (match.index > last) out.push(['t', text.slice(last, match.index)]);
        last = match.index + match[0].length;
        const [, bold, starItalic, underscoreItalic, linkText, linkUrl, bareUrl, colorId, colored, markId, marked] = match;
        if (markId !== undefined) out.push(['m', markId, tokens(marked)]);
        else if (colorId !== undefined) out.push(['c', colorId, tokens(colored)]);
        else if (bold !== undefined) out.push(['b', tokens(bold)]);
        else if (starItalic !== undefined || underscoreItalic !== undefined) out.push(['i', tokens(starItalic ?? underscoreItalic)]);
        else {
            const url = linkUrl ?? bareUrl;
            let ok = true;
            try { const parsed = new URL(url); ok = parsed.protocol === 'https:' || parsed.protocol === 'http:'; } catch { ok = false; }
            out.push(ok ? ['l', linkText ?? bareUrl] : ['t', match[0]]);
        }
    }
    if (last < text.length) out.push(['t', text.slice(last)]);
    return out;
}

// One compact string per line; adjacent text is merged and empty text dropped, so only the structure matters.
function serialize(list) {
    const merged = [];
    for (const token of list) {
        const previous = merged[merged.length - 1];
        if (token[0] === 't' && previous && previous[0] === 't') previous[1] += token[1];
        else merged.push(token[0] === 't' ? ['t', token[1]] : token);
    }
    return merged.filter(token => !(token[0] === 't' && token[1] === '')).map(token => {
        switch (token[0]) {
            case 't': return `t${JSON.stringify(token[1])}`;
            case 'l': return `l${JSON.stringify(token[1])}`;
            case 'b': case 'i': return `${token[0]}[${serialize(token[1])}]`;
            default: return `${token[0]}:${token[1]}[${serialize(token[2])}]`;
        }
    }).join(',');
}

const corpus = [
    '**bold**', 'a **bold** b', '**bold**text', 'text**bold**', '** spaced **', '**unclosed', '**', '****',
    '*italic*', '_italic_', 'snake_case_name', '2*3*4', 'a * b * c', '* not italic *', '*not closed', '__dunder__',
    '**bold *nested italic* bold**', '*italic **bold** italic*', '***triple***', '**_both_**', '_**both**_', '**bold**_italic_',
    '**bold {red|red} bold**', '{red|**bold red**}', '{=gold|**marked bold**}', '{red|a} {=teal|b}', '{blue|x}', '{red|}', '{red|unclosed',
    '**[link](https://x.com)**', '[**bold link**](https://x.com)', '[plain](https://x.com/a?b=1)', '[bad](ftp://x.com)',
    'see **John 3:16**', '**ação**', '**Olá!**', '**a** **b**', '**a**, *b*, _c_', '**line with * star**',
    '**bold**: text', '(**bold**)', '"**quoted**"', '**1.** item', '**bold**.', '**a*b**', '*a**b*',
    'https://example.com/a.b, then', '**https://example.com**', 'visit https://biblewish.com today', 'a_b_c and *d*',
    '**Matthew 5:3-12** and *Luke 2*', '**bold** and {red|colored **bold**} and _it_', 'He said **"Come."**', '**❤ heart**',
];

const lines = corpus.map(line => `        (${JSON.stringify(line)}, ${JSON.stringify(serialize(tokens(line)))}),`);
writeFileSync(join(root, 'BibleWish', 'Sync', 'NoteInlineFixtures.swift'), `//
//  NoteInlineFixtures.swift
//
//  GENERATED by tools/gen_note_fixtures.mjs from the website's own note formatter. Do not edit.
//  Debug builds only; used by the self-test to check NoteInline against the website.
//

#if DEBUG
enum NoteInlineFixtures {
    /// (line, how the website splits it)
    static let cases: [(String, String)] = [
${lines.join('\n')}
    ]
}
#endif
`);
console.log(`wrote ${corpus.length} cases; colors: ${NOTE_COLORS.map(c => c.id).join(', ')}`);
